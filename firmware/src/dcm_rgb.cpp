void RGB_LED_3D::initialize_from_config()
{
    uint32_t loop_index = 0;
    for (auto & element : string_vec) {
        // scan config for match for each element
        struct string_led_config lookup_result = lookup_pos_config(loop_index);
        if (lookup_result.string_position == loop_index)
        {
            // good match
            element->set_coordinates_from_config(lookup_result);
            printf("config read for string index: ");
            printf("%d\n", loop_index);
            printf("w: ");
            printf("%d\n", lookup_result.coordinates.omega);
            printf("r: ");
            printf("%d\n", lookup_result.coordinates.radius);
            printf("z: ");
            printf("%d\n", lookup_result.coordinates.z);
        }
        else
        {
            printf("no config found for string index: ");
            printf("%d\n", loop_index);
        }
        ++loop_index;
    }    
}

void RGB_LED_3D::set_secondary_RGB(dcm_rgb_data rgb_data_in, bool clear_on_zero)
{
    // if new data is all zeros, toggle away from secondary
    if (rgb_data_in.word == 0 && clear_on_zero)
    {
        secondary_toggle = false;
    }
    else
    {
        rgb_data_secondary = rgb_data_in;
        secondary_toggle = true;
    }
}

void RGB_LED_3D::set_secondary_toggle(bool toggle_in)
{
    // Declared and called in several places (update_ALL(), toggle_single_led(),
    // and now update_volume_cartesian/cylindrical) but never actually defined -
    // dead-code elimination (--gc-sections) had been silently stripping every
    // one of those call sites since none of them were reachable from a live
    // path, so the missing definition never showed up as a link error until
    // now, with the first caller that's actually exercised.
    secondary_toggle = toggle_in;
}

void toggle_single_led(uint16_t pos_in)
{
    RGB_LED_3D::update_ALL();
    // fetch pointer to object at position
    RGB_LED_3D* target_led = RGB_LED_3D::string_vec.at(pos_in);
    target_led->set_secondary_toggle(true);
}

uint32_t RGB_LED_3D::get_grb_word()
{
    if (secondary_toggle)
    {
        rgb_data_output = rgb_data_secondary;
    }
    else
    {
        //rgb_data_output = rgb_data_base;
        rgb_data_output.bytes.green = rgb_data_base.bytes.green >> 0;
        rgb_data_output.bytes.red = rgb_data_base.bytes.red >> 0;
        rgb_data_output.bytes.blue = rgb_data_base.bytes.blue >> 0;
        rgb_data_output.bytes.garbo = rgb_data_base.bytes.garbo;
    }
    return rgb_data_output.word;
}

